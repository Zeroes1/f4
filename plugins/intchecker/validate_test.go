func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func TestParseHashFileReadsWhatFormatHashFileWrites(t *testing.T) {
	names := []string{"a.txt", "with space.bin", `back\slash`, "line\nbreak", "sub/dir.txt"}
	for a := range algorithms {
		alg := Algorithm(a)
		var entries []Entry
		for _, name := range names {
			if alg == AlgCRC32 && strings.Contains(name, "\n") {
				continue // SFV cannot store it
			}
			entries = append(entries, Entry{Name: name, Sum: mustHex(t, abcDigests[alg])})
		}
		data, err := FormatHashFile(alg, entries)
		if err != nil {
			t.Fatal(err)
		}
		got, err := ParseHashFile("list"+alg.Extension(), data)
		if err != nil {
			t.Fatalf("%s: %v", alg.Name(), err)
		}
		if got.Algorithm != alg || got.Malformed != 0 || len(got.Entries) != len(entries) {
			t.Fatalf("%s: parsed %+v", alg.Name(), got)
		}
		for i, e := range entries {
			if got.Entries[i].Name != e.Name || !bytes.Equal(got.Entries[i].Sum, e.Sum) {
				t.Errorf("%s: entry %d = %q %x, want %q %x", alg.Name(), i, got.Entries[i].Name, got.Entries[i].Sum, e.Name, e.Sum)
			}
		}
	}
}

func TestParseHashFileAcceptsOtherToolsLines(t *testing.T) {
	md5 := abcDigests[AlgMD5]
	data := "\xef\xbb\xbf# comment\r\n" +
		md5 + "  text mode.txt\r\n" +
		md5 + " single.txt\n" +
		strings.ToUpper(md5) + " *upper.txt\n" +
		"\n   \n" +
		"garbage line\n" +
		md5 + " *\n"
	got, err := ParseHashFile("LIST.MD5", []byte(data))
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"text mode.txt", "single.txt", "upper.txt"}
	if got.Algorithm != AlgMD5 || len(got.Entries) != len(want) || got.Malformed != 2 {
		t.Fatalf("parsed %+v", got)
	}
	for i, name := range want {
		if got.Entries[i].Name != name {
			t.Errorf("entry %d = %q, want %q", i, got.Entries[i].Name, name)
		}
	}
}

func TestParseHashFileReadsSFV(t *testing.T) {
	data := "; Generated by some tool\n" +
		"name with spaces.txt 352441C2\n" +
		"tabbed.txt\t352441c2  \n" +
		"nocrc.txt\n"
	got, err := ParseHashFile("disk.sfv", []byte(data))
	if err != nil {
		t.Fatal(err)
	}
	if got.Algorithm != AlgCRC32 || len(got.Entries) != 2 || got.Malformed != 1 ||
		got.Entries[0].Name != "name with spaces.txt" || got.Entries[1].Name != "tabbed.txt" {
		t.Fatalf("parsed %+v", got)
	}
}

func TestParseHashFilePicksAlgorithmByLength(t *testing.T) {
	for _, tc := range []struct {
		name string
		sum  string
		want Algorithm
	}{
		{"checksums.txt", abcDigests[AlgSHA1], AlgSHA1},
		{"mislabelled.md5", abcDigests[AlgSHA256], AlgSHA256},
		{"noext", abcDigests[AlgSHA384], AlgSHA384},
		{"CHECKSUMS", abcDigests[AlgSHA512], AlgSHA512},
		{"crc.txt", abcDigests[AlgCRC32], AlgCRC32},
	} {
		got, err := ParseHashFile(tc.name, []byte(tc.sum+" *a.txt\n"))
		if err != nil {
			t.Fatalf("%s: %v", tc.name, err)
		}
		if got.Algorithm != tc.want || len(got.Entries) != 1 {
			t.Errorf("%s: algorithm %s, entries %d; want %s", tc.name, got.Algorithm.Name(), len(got.Entries), tc.want.Name())
		}
	}
}

