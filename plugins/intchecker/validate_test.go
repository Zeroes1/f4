// validateFixture is a directory with a.txt ("abc", matches), b.txt (changed
// since), sub/d.txt (matches) and a directory "dir", plus the checksum list
// for a.txt, b.txt, c.txt (missing), dir and sub/d.txt.
func validateFixture(t *testing.T) (string, ChecksumFile) {
	t.Helper()
	dir := t.TempDir()
	writeTestFile(t, dir, "a.txt", "abc")
	writeTestFile(t, dir, "b.txt", "abd")
	if err := os.Mkdir(filepath.Join(dir, "sub"), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(filepath.Join(dir, "dir"), 0o700); err != nil {
		t.Fatal(err)
	}
	writeTestFile(t, dir, filepath.Join("sub", "d.txt"), "abc")
	sum := mustHex(t, abcDigests[AlgSHA256])
	file := ChecksumFile{Algorithm: AlgSHA256, Entries: []Entry{
		{Name: "a.txt", Sum: sum},
		{Name: "b.txt", Sum: sum},
		{Name: "c.txt", Sum: sum},
		{Name: "dir", Sum: sum},
		{Name: "sub/d.txt", Sum: sum},
	}}
	return dir, file
}

func TestRunValidateSortsEveryFileIntoAVerdict(t *testing.T) {
	dir, file := validateFixture(t)
	reporter := &recordingReporter{}
	job := validateJob{fs: vfs.NewOSVFS(dir), dir: dir, file: file}
	res, err := runValidate(context.Background(), job, reporter)
	if err != nil {
		t.Fatal(err)
	}
	want := []entryStatus{statusOK, statusMismatch, statusMissing, statusReadError, statusOK}
	if len(res.Results) != len(want) {
		t.Fatalf("results = %+v", res.Results)
	}
	for i, status := range want {
		if res.Results[i].Name != file.Entries[i].Name || res.Results[i].Status != status {
			t.Errorf("result %d = %+v, want %s %d", i, res.Results[i], file.Entries[i].Name, status)
		}
	}
	if res.Counts != [statusCount]int{2, 1, 1, 1} {
		t.Fatalf("counts = %v", res.Counts)
	}
	if reporter.lastTotal != 100 || !reporter.files["sub/d.txt"] {
		t.Fatalf("progress = %+v", reporter)
	}
}

