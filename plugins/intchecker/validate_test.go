func TestParseHashFileErrors(t *testing.T) {
	if _, err := ParseHashFile("x.md5", []byte("; nothing\n\n")); !errors.Is(err, errNoChecksums) {
		t.Fatalf("empty file: err = %v", err)
	}
	if _, err := ParseHashFile("x.txt", []byte("0011223344 *a\n")); !errors.Is(err, errUnknownHashLength) {
		t.Fatalf("5-byte digest: err = %v", err)
	}
	if _, err := ParseHashFile("x.md5", []byte(`\`+abcDigests[AlgMD5]+` *bad\qescape`+"\n")); !errors.Is(err, errNoChecksums) {
		t.Fatalf("bad escape: err = %v", err)
	}
}

